#!/usr/bin/env python3
"""Copy the user-requested non-commercial dsh-pet pack, preserving source hashes."""
import hashlib,json,shutil
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT.parent.parent/'ref/dsh-pet/dsh-pet/assets/webm'
ASSETS=ROOT/'assets/dsh-pet-desktop-v1'
WEB=ROOT/'MALFOY-ENGINE/web/live2d/dsh-motion'
CATALOG=json.loads((ASSETS/'catalog.json').read_text())
notice='''# dsh-pet 桌面动作包

按用户 2026-11-01 授权，复用 PC2005-cloud/dsh-pet 的透明动画用于本地非商业伙伴。
上游：https://github.com/PC2005-cloud/dsh-pet
代码 MIT；动画/提示词/源视频允许开源使用，禁止商用，公开二创须附原作者 GitHub 地址。
形象为社区二创 DeepSeek「大肥鱼」，非 DeepSeek 官方，非澜原创资产。
原型「溟月」：B站 @上善无形 https://space.bilibili.com/4456176
DeepSeek 版设计：B站 @ZipZipPipe https://space.bilibili.com/4168597
形象：CC BY-NC-SA 4.0 https://creativecommons.org/licenses/by-nc-sa/4.0/deed.zh-hans
上游声明：https://www.bilibili.com/opus/1247156596114456581
本包仅接入本机非商业版本；公开发布仍需项目整体素材审计，并保留署名与相同方式共享条件。
上游动作保持原片；generated.json 所列新增动作 为 imagegen 基于该形象绘制的二创序列帧（非上游原片、非连续生成视频），原图/帧序/锚点/派生方法记录在 generated/ 与 generated.json，按同一非商业相同方式共享条件使用。
播放器静音；哼歌/聊天动画本身不带人声，读书/歌曲/回复音频仍由现有媒体服务播放。manifest 记录原路径及 SHA256。
'''
for d in [ASSETS,WEB]: d.mkdir(parents=True,exist_ok=True)
rows={}
for key,entry in CATALOG.items():
 src=SOURCE/entry['source']; dest=ASSETS/(key+'.webm');shutil.copy2(src,dest);shutil.copy2(dest,WEB/dest.name)
 rows[key]={'file':dest.name,'label':entry['label'],'category':entry['category'],'hidden':entry.get('hidden',False),'sourceFile':src.name,'sha256':hashlib.sha256(dest.read_bytes()).hexdigest(),'bytes':dest.stat().st_size}
generated=ASSETS/'generated.json'
if generated.exists():
 for key,item in json.loads(generated.read_text()).items():
  src=ASSETS/item['file'];shutil.copy2(src,WEB/src.name)
  rows[key]={**item,'sha256':hashlib.sha256(src.read_bytes()).hexdigest(),'bytes':src.stat().st_size}
data={'source':'https://github.com/PC2005-cloud/dsh-pet','revision':'8ad3d957f83052d332f0d0f09e90993e9756d2ec','license':'Animations non-commercial; character CC BY-NC-SA 4.0','actions':rows}
for d in [ASSETS,WEB]:
 (d/'manifest.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n');(d/'NOTICE.md').write_text(notice)
print(f'{len(rows)} actions; {sum(r["bytes"] for r in rows.values())/1024/1024:.1f} MiB; copies match source')

public={k:{'label':r['label'],'category':r['category'],'generated':bool(r.get('method')),'anchorY':r.get('anchorY',330)} for k,r in rows.items() if not r.get('hidden')}
module='/* Generated by prepare-dsh-desktop.py; edit assets catalog.json / generated.json. */\n(function(root,factory){const api=factory();if(typeof module===\"object\"&&module.exports)module.exports=api;else root.DshCatalog=api;})(globalThis,function(){return '+json.dumps(public,ensure_ascii=False,separators=(',',':'))+';});\n'
(ROOT/'MALFOY-ENGINE/web/live2d/dsh-catalog.js').write_text(module)
# Sound is a separate source contract, never covered by the character art license.
special=json.loads((ASSETS/'special-idle.json').read_text())
tracks={}
for key,track in special['tracks'].items():
 src=ASSETS/track['file']
 assert hashlib.sha256(src.read_bytes()).hexdigest()==track['sha256']
 shutil.copy2(src,WEB/src.name)
 tracks[key]={'url':'./dsh-motion/'+src.name,'label':track['label'],'duration':track['duration']}
(WEB/'special-idle.json').write_text(json.dumps(special,ensure_ascii=False,indent=2)+'\n')
(ROOT/'MALFOY-ENGINE/web/live2d/dsh-idle-media.js').write_text('/* Generated; audio provenance: dsh-motion/special-idle.json */\nglobalThis.DshIdleMedia='+json.dumps({'defaultTrack':special['defaultTrack'],'tracks':tracks},ensure_ascii=False)+';\n')
for directory in [ASSETS,WEB]:
 with (directory/'NOTICE.md').open('a') as f:f.write('\n闲置哼唱见 special-idle.json：用户提供的抖音参考原音为本地提取，音频不属于上面的角色美术许可；另保留旧合成音可选，未核实原音再分发授权。\n')
